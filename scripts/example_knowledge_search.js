/**
 * Example: ClickUp Brain Knowledge Synthesis & Standup Digest
 * Demonstrates how the Librarian agent queries task activities and comment threads to synthesize a daily standup.
 */

const ClickUpClient = require('./clickup_api_helper');

async function main() {
  const token = process.env.CLICKUP_API_TOKEN;
  if (!token) {
    console.log('[-] CLICKUP_API_TOKEN environment variable not set.');
    console.log('    Run: $env:CLICKUP_API_TOKEN = "pk_your_token"');
    console.log('\n[Demo Mode] Generating simulated Daily Standup Digest:\n');
    console.log(generateSampleStandup());
    return;
  }

  const client = new ClickUpClient(token);
  console.log('[+] Fetching workspaces for Knowledge Digest...');
  const { teams } = await client.getWorkspaces();
  if (!teams || teams.length === 0) {
    console.log('[-] No authorized workspaces found.');
    return;
  }

  const teamId = teams[0].id;
  const { spaces } = await client.getSpaces(teamId);
  if (!spaces || spaces.length === 0) {
    console.log('[-] No spaces found.');
    return;
  }

  const space = spaces[0];
  console.log(`[+] Scanning Space: "${space.name}"...`);

  // Fetch tasks
  const folderless = await client.getFolderlessLists(space.id);
  let list = folderless.lists && folderless.lists[0];
  if (!list) {
    const { folders } = await client.getFolders(space.id);
    if (folders && folders.length > 0) {
      const folderLists = await client.getListsInFolder(folders[0].id);
      list = folderLists.lists && folderLists.lists[0];
    }
  }

  if (!list) {
    console.log('[-] No lists found in Space.');
    return;
  }

  console.log(`[+] Querying tasks from List: "${list.name}"...`);
  const taskRes = await client.getTasks(list.id, { archived: false, subtasks: true });
  const tasks = taskRes.tasks || [];

  console.log(`[+] Retrieved ${tasks.length} tasks. Synthesizing Knowledge Report...\n`);

  const completed = tasks.filter(t => t.status && (t.status.status.toLowerCase() === 'done' || t.status.status.toLowerCase() === 'closed'));
  const inProgress = tasks.filter(t => t.status && t.status.status.toLowerCase().includes('progress'));
  const urgent = tasks.filter(t => t.priority && t.priority.id === '1');

  console.log('======================================================');
  console.log(`📊 DAILY WORKSPACE DIGEST: ${space.name.toUpperCase()}`);
  console.log('======================================================\n');

  console.log(`🚀 COMPLETED TASKS (${completed.length})`);
  completed.slice(0, 5).forEach(t => console.log(`  • [${t.id}] ${t.name} (Assignee: ${t.assignees.map(a => a.username).join(', ') || 'Unassigned'})`));
  if (completed.length === 0) console.log('  (No tasks completed in this window)');

  console.log(`\n🔄 ACTIVE / IN PROGRESS (${inProgress.length})`);
  inProgress.slice(0, 5).forEach(t => console.log(`  • [${t.id}] ${t.name} -> ${t.status.status}`));
  if (inProgress.length === 0) console.log('  (No tasks currently in progress)');

  console.log(`\n⚠️ URGENT ESCALATIONS (${urgent.length})`);
  urgent.forEach(t => console.log(`  • [CRITICAL] ${t.name} (URL: ${t.url})`));
  if (urgent.length === 0) console.log('  (Zero urgent blockers reported)');

  console.log('\n======================================================');
  console.log('[✓] Synthesis generated by [Librarian Knowledge Agent]');
}

